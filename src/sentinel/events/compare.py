"""Comparison of the preliminary events with feature 001's provisional events (research.md R8;
FR-016, SC-005).

Feature 001's events are read as a file; `sentinel.provisional` is never imported. Production is
counted in variants that each move one rule towards feature 001's, so every step's gap belongs to
that rule:
1. production: the full rules;
2. + $2: only events whose member lines are all priced at $2 or more (feature 001's stand-in);
3. − O/D: clusters also without the officer-or-director condition;
4. pilot G6: also with feature 001's minimum per filing (`provisional.filing_min_value`, D46).
The gap between variant 4 and feature 001 is left to point-in-time entities and valuation, and
years where it exceeds 15% are flagged for a hand-written explanation.
"""

from dataclasses import dataclass
from pathlib import Path

import duckdb
import pyarrow.parquet as pq

from sentinel.config import registered_value
from sentinel.events.prelim import find_events

GROUPS = ("A", "B1", "B2")
FLAG = 0.15  # SC-005: a larger gap needs an explanation
EXPLANATIONS = "\n## Explanations"


@dataclass(frozen=True)
class Row:
    year: int
    provisional: int | None  # None: feature 001 has no such group (B2)
    variants: tuple[int, int, int, int]

    @property
    def gap(self) -> float | None:
        """(variant 4 − feature 001) ÷ feature 001."""
        if not self.provisional:
            return None
        return (self.variants[-1] - self.provisional) / self.provisional

    @property
    def flagged(self) -> bool:
        return self.gap is not None and abs(self.gap) > FLAG


def _counts(con: duckdb.DuckDBPyConnection, table: str, where: str = "true") -> dict:
    return {
        (g, y): n
        for g, y, n in con.execute(
            f'select "group", year(signal_date), count(*) from {table} where {where} group by all'
        ).fetchall()
    }


def tabulate(
    con: duckdb.DuckDBPyConnection, parquet_path: Path, params: dict
) -> dict[str, list[Row]]:
    """Per group, one row per year with feature 001's count and the four production variants."""
    con.register("_provisional", pq.read_table(parquet_path, columns=["group", "signal_date"]))
    try:
        provisional = _counts(con, "_provisional")
    finally:
        con.unregister("_provisional")
    variants = [_counts(con, "evt.prelim_event")]
    variants.append(_counts(con, "evt.prelim_event", "passes_price_standin"))
    find_events(con, params, officer_or_director=False)
    variants.append(_counts(con, "_events", "passes_price_standin"))
    con.execute(
        """
        create or replace temp table _pilot_clean as
        with c as (
            select accession, issuer_cik, filing_date, quarter, sum(value_usd) as value_usd
            from core.transaction where passes_lines
            group by all having sum(value_usd) >= $floor
        )
        select c.accession, c.issuer_cik, c.filing_date, c.value_usd,
               list_sort(list_distinct(list(o.rptownercik))) as owner_ciks
        from c left join stg.reportingowner o
          on o.accession_number = c.accession and o.quarter = c.quarter
        group by all
        """,
        {"floor": params["provisional"]["filing_min_value"]},
    )
    find_events(con, params, purchases="_pilot_clean", officer_or_director=False)
    variants.append(_counts(con, "_events", "passes_price_standin"))
    for name in ("_pilot_clean", "_window", "_window_entity", "_events", "_event_members"):
        con.execute(f"drop table if exists {name}")

    table = {}
    for group in GROUPS:
        keys = set(provisional) | {k for v in variants for k in v}
        years = sorted(y for g, y in keys if g == group)
        table[group] = [
            Row(
                year=y,
                provisional=None if group == "B2" else provisional.get((group, y), 0),
                variants=tuple(v.get((group, y), 0) for v in variants),
            )
            for y in years
        ]
    return table


def _pct(x: float | None) -> str:
    return "—" if x is None else f"{100 * x:+.1f}%".replace("-", "−")


def _line(cells) -> str:
    return "| " + " | ".join(str(c) for c in cells) + " |"


def render(table: dict[str, list[Row]], params: dict, parquet_name: str) -> str:
    pilot = f"${params['provisional']['filing_min_value']:,}"
    production = f"${registered_value(params, 'g6_min_value'):,}"
    head = ["Year", "Feature 001", "Production", "+ $2", "− O/D", f"G6 {pilot}", "Gap", "Flag"]
    totals = {g: [sum(r.variants[i] for r in rows) for i in range(4)] for g, rows in table.items()}
    a_feature001 = sum(r.provisional or 0 for r in table["A"])
    sc005 = totals["A"][1] <= a_feature001
    out = [
        "# Comparison: preliminary events vs feature 001's provisional events",
        "",
        f"Generated by `sentinel compare-provisional` from `{parquet_name}` and `evt.prelim_event`"
        f" (params version {params['version']}). Counts are events per signal year.",
        "",
        "Each production column moves one rule towards feature 001's, so the change from the "
        "column before it belongs to that rule:",
        f"- **Production**: the full rules (G6 minimum {production} per filing).",
        "- **+ $2**: only events whose member lines are all priced at $2 or more, feature 001's "
        "stand-in for the price floor.",
        "- **− O/D**: clusters also without the officer-or-director condition.",
        f"- **G6 {pilot}**: also with feature 001's minimum per filing (D46 raised it).",
        "",
        "**Gap** compares the last column with feature 001; what remains comes from point-in-time "
        "entities and per-filing valuation. ⚠ marks gaps above 15%, which need an explanation "
        "below. Feature 001 had no B2 group.",
        "",
        f"**SC-005**: A events under production + $2 = {totals['A'][1]:,}, against feature 001's "
        f"{a_feature001:,}: {'✅ not more' if sc005 else '❌ more'}.",
    ]
    for group, rows in table.items():
        prov_total = None if group == "B2" else sum(r.provisional for r in rows)
        total = Row(0, prov_total, tuple(totals[group]))
        out += ["", f"## {group}", "", _line(head), _line(["---"] * len(head))]
        for r in [*rows, total]:
            year = "**Total**" if r is total else r.year
            prov = "—" if r.provisional is None else f"{r.provisional:,}"
            cells = [year, prov, *(f"{n:,}" for n in r.variants), _pct(r.gap)]
            out.append(_line([*cells, "⚠" if r.flagged else ""]))
    out += ["", EXPLANATIONS[1:], "", "_One entry per ⚠ year, written by hand after the run._", ""]
    return "\n".join(out)


def compare(con: duckdb.DuckDBPyConnection, parquet_path: Path, params: dict) -> str:
    return render(tabulate(con, parquet_path, params), params, Path(parquet_path).name)


def write_report(path: Path, report: str) -> None:
    """Write `report`, keeping the hand-written Explanations section of an existing file."""
    if path.exists() and EXPLANATIONS in (old := path.read_text(encoding="utf-8")):
        report = report[: report.index(EXPLANATIONS)] + old[old.index(EXPLANATIONS) :]
    path.write_text(report, encoding="utf-8")
