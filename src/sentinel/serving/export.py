"""`sentinel export`: a Parquet snapshot in `data/exports/` for sharing privately (it holds
Tiingo-derived prices, so it is never published) and for model work outside DuckDB.

- `ml/`: one training set per risk question, features joined to their label: `volatility` and
  `dilution` (month-end rows), `results_move` (release-eve rows); `latest` (each company's latest
  row, for scoring); and `feature_snapshot`, every feature row (the holdout's rows from 2023 have
  features but no labels). Rows keep `eligible`; the models learn from the eligible ones.
- `app/`: every table of `data/serving.duckdb`.
- `README.md`: generated; each file with its rows and columns.
"""

import shutil

import duckdb

from sentinel import db
from sentinel.config import Paths

ML = {
    "volatility": """
        select s.*, l.vol_63_future, l.window_end from b.feature.snapshot s
        join b.label.volatility l using (cik, as_of) where s.month_end order by s.cik, s.as_of
    """,
    "dilution": """
        select s.*, l.dilution, l.window_end from b.feature.snapshot s
        join b.label.dilution l using (cik, as_of) where s.month_end order by s.cik, s.as_of
    """,
    "results_move": """
        select s.*, l.filing_date, l.report_date, l.close_after, l.move, l.prev4_mean, l.n_prev
        from b.feature.snapshot s join b.label.results_move l using (cik, as_of)
        order by s.cik, l.filing_date
    """,
    "latest": "select * from b.feature.snapshot where latest order by cik",
    "feature_snapshot": "select * from b.feature.snapshot order by cik, as_of",
}


def export(p: Paths, echo=print) -> dict:
    """Write the Parquet snapshot; returns rows per file."""
    for f in (p.build_db, p.serving_db):
        if not f.exists():
            raise FileNotFoundError(f"{f} not found: run `sentinel build` and `sentinel publish`")
    tmp = p.exports.with_name("exports.tmp")
    shutil.rmtree(tmp, ignore_errors=True)
    (tmp / "ml").mkdir(parents=True)
    (tmp / "app").mkdir()
    rows: dict[str, tuple[int, list[tuple[str, str]]]] = {}
    with duckdb.connect(config={"memory_limit": db.MEMORY_LIMIT}) as con:
        con.execute(f"attach '{p.build_db.as_posix()}' as b (read_only)")
        con.execute(f"attach '{p.serving_db.as_posix()}' as s (read_only)")
        db.require(con, ["label.volatility", "label.dilution", "label.results_move"],
                   "sentinel export")  # fmt: skip
        apps = [r[0] for r in con.execute(
            "select table_name from duckdb_tables() where database_name = 's' "
            "and schema_name = 'app' order by 1").fetchall()]  # fmt: skip
        jobs = [(f"ml/{k}.parquet", sql) for k, sql in ML.items()]
        jobs += [(f"app/{t}.parquet", f"select * from s.app.{t}") for t in apps]
        for name, sql in jobs:
            con.execute(f"copy ({sql}) to '{(tmp / name).as_posix()}' "
                        "(format parquet, compression zstd)")  # fmt: skip
            described = con.execute(f"describe select * from '{(tmp / name).as_posix()}'")
            columns = [(c, t) for c, t, *_ in described.fetchall()]
            n = con.execute(f"select count(*) from '{(tmp / name).as_posix()}'").fetchone()[0]
            rows[name] = (n, columns)
            echo(f"  {name}: {n:,} rows")
    (tmp / "README.md").write_text(_readme(rows), encoding="utf-8")
    shutil.rmtree(p.exports, ignore_errors=True)
    tmp.rename(p.exports)
    return {name: n for name, (n, _) in rows.items()}


def _readme(rows: dict[str, tuple[int, list[tuple[str, str]]]]) -> str:
    lines = [
        "# Data export (private)",
        "",
        "Written by `sentinel export`; do not edit. Holds Tiingo-derived prices: share privately,",
        "never publish. Definitions: `docs/architecture.md`, `src/sentinel/features/`,",
        "`src/sentinel/labels/risk.py`, `config/risk_params.yaml`.",
        "",
        "| File | Rows | Columns |",
        "|---|---:|---:|",
        *(f"| `{name}` | {n:,} | {len(cols)} |" for name, (n, cols) in rows.items()),
    ]
    for name, (_, cols) in rows.items():
        lines += ["", f"## `{name}`", "", ", ".join(f"`{c}` ({t.lower()})" for c, t in cols)]
    return "\n".join(lines) + "\n"


def _readme_reference(rows: dict[str, tuple[int, list[tuple[str, str]]]]) -> str:
    lines = [
        "# Reference Datasets (Private, Feature 002)",
        "",
        "Generated by `sentinel export --reference`. Contains all historical and holdout years",
        "(2012–present) with unsealed answers wherever windows have closed, plus a `period` column",
        "(`development`, `gap`, `holdout`).",
        "",
        "**Strict Rule (Constitution IV & Decision V2-21)**: These reference files are for private",
        "personal analysis, auditing and validation only. Models are trained and selected strictly",
        "on `data/exports/ml/` and must never read these reference files.",
        "",
        "| File | Rows | Columns |",
        "|---|---:|---:|",
        *(f"| `{name}` | {n:,} | {len(cols)} |" for name, (n, cols) in rows.items()),
    ]
    for name, (_, cols) in rows.items():
        lines += ["", f"## `{name}`", "", ", ".join(f"`{c}` ({t.lower()})" for c, t in cols)]
    return "\n".join(lines) + "\n"


def export_reference(p: Paths, echo=print) -> dict[str, int]:
    """Write private reference datasets with unsealed answers and period (002)."""
    if not p.build_db.exists():
        raise FileNotFoundError(f"{p.build_db} not found: run `sentinel build`")

    ref_dir = p.exports / "reference"
    tmp = p.exports.with_name("reference.tmp")
    shutil.rmtree(tmp, ignore_errors=True)
    tmp.mkdir(parents=True)

    import pandas as pd

    from sentinel.labels.risk import _days, month_labels, results_moves, risk_params, share_steps

    rules = risk_params(p)
    rows: dict[str, tuple[int, list[tuple[str, str]]]] = {}

    with duckdb.connect(config={"memory_limit": db.MEMORY_LIMIT}) as con:
        con.execute(f"attach '{p.build_db.as_posix()}' as b (read_only)")
        db.require(
            con,
            [
                "feature.snapshot",
                "feature.row",
                "core.price_daily",
                "core.shares_outstanding",
                "core.results_release",
                "ref.calendar",
                "stg_yahoo.price",
            ],
            "sentinel export --reference",
        )

        cal_df = con.execute("select session from b.ref.calendar order by 1").df()
        calendar = _days(cal_df["session"])
        last_session = con.execute("select max(session) from b.ref.calendar").fetchone()[0]
        gap = int(rules["labels"]["results_move"]["max_report_gap_days"])
        spy_sql = (
            "select session, adj_close from b.stg_yahoo.price "
            "where ticker = 'SPY' and adj_close > 0 order by 1"
        )
        spy = con.execute(spy_sql).df()

        con.execute(
            "create or replace temp table _ref_month (cik VARCHAR, as_of DATE, "
            "vol_63_future DOUBLE, vol_window_end DATE, dilution DOUBLE, "
            "dilution_window_end DATE)"
        )
        con.execute(
            "create or replace temp table _ref_results_move (cik VARCHAR, filing_date DATE, "
            "report_date DATE, as_of DATE, close_after DATE, move DOUBLE, prev4_mean DOUBLE, "
            "n_prev INTEGER)"
        )

        ciks = [
            r[0]
            for r in con.execute(
                "select distinct cik from b.feature.row where month_end or release_eve order by 1"
            ).fetchall()
        ]

        echo(f"  Computing reference labels through {last_session} across {len(ciks):,} filers...")
        chunk_size = 400
        for i in range(0, len(ciks), chunk_size):
            chunk_ciks = ciks[i : i + chunk_size]
            daily_sql = (
                "select cik, session, adj_close, cum_split_after from b.core.price_daily "
                "where not glitch and adj_close > 0 and close > 0 "
                "and cik in (select unnest(?::VARCHAR[]))"
            )
            daily = con.execute(daily_sql, [chunk_ciks]).df()
            rows_sql = (
                "select cik, as_of from b.feature.row where month_end "
                "and cik in (select unnest(?::VARCHAR[]))"
            )
            m_rows = con.execute(rows_sql, [chunk_ciks]).df()
            shares = con.execute(
                "select cik, as_of as period_end, shares as value, filed "
                "from b.core.shares_outstanding where cik in (select unnest(?::VARCHAR[]))",
                [chunk_ciks],
            ).df()
            for c in ("period_end", "filed"):
                shares[c] = pd.to_datetime(shares[c])
            releases = con.execute(
                "select cik, filing_date, report_date from b.core.results_release "
                "where cik in (select unnest(?::VARCHAR[]))",
                [chunk_ciks],
            ).df()

            lbls = month_labels(daily, m_rows, calendar, share_steps(shares), rules, last_session)
            moves = results_moves(daily, releases, calendar, spy, last_session, gap)

            if len(lbls):
                con.register("_mchunk", lbls)
                con.execute("insert into _ref_month select * from _mchunk")
                con.unregister("_mchunk")
            if len(moves):
                con.register("_mvchunk", moves)
                con.execute("insert into _ref_results_move select * from _mvchunk")
                con.unregister("_mvchunk")

        dev_cond_vol = "s.as_of <= '2022-12-31' and l.vol_window_end <= '2022-12-31'"
        gap_cond_vol = (
            "s.as_of <= '2022-12-31' and (l.vol_window_end > '2022-12-31' "
            "or l.vol_window_end is null)"
        )
        dev_cond_dil = "s.as_of <= '2022-12-31' and l.dilution_window_end <= '2022-12-31'"
        gap_cond_dil = (
            "s.as_of <= '2022-12-31' and (l.dilution_window_end > '2022-12-31' "
            "or l.dilution_window_end is null)"
        )
        dev_cond_res = "s.as_of <= '2022-12-31' and l.close_after <= '2022-12-31'"
        gap_cond_res = (
            "s.as_of <= '2022-12-31' and (l.close_after > '2022-12-31' or l.close_after is null)"
        )

        ref_queries = {
            "volatility": f"""
                select
                    s.*,
                    l.vol_63_future,
                    l.vol_window_end as window_end,
                    case
                        when {dev_cond_vol} then 'development'
                        when {gap_cond_vol} then 'gap'
                        else 'holdout'
                    end as period
                from b.feature.snapshot s
                join _ref_month l using (cik, as_of)
                where s.month_end and l.vol_window_end is not null
                order by s.cik, s.as_of
            """,
            "dilution": f"""
                select
                    s.*,
                    l.dilution,
                    l.dilution_window_end as window_end,
                    case
                        when {dev_cond_dil} then 'development'
                        when {gap_cond_dil} then 'gap'
                        else 'holdout'
                    end as period
                from b.feature.snapshot s
                join _ref_month l using (cik, as_of)
                where s.month_end and l.dilution_window_end is not null
                order by s.cik, s.as_of
            """,
            "results_move": f"""
                select
                    s.*,
                    l.filing_date,
                    l.report_date,
                    l.close_after,
                    l.move,
                    l.prev4_mean,
                    l.n_prev,
                    case
                        when {dev_cond_res} then 'development'
                        when {gap_cond_res} then 'gap'
                        else 'holdout'
                    end as period
                from b.feature.snapshot s
                join _ref_results_move l using (cik, as_of)
                order by s.cik, l.filing_date
            """,
        }

        for name, sql in ref_queries.items():
            out_file = tmp / f"{name}.parquet"
            copy_sql = f"copy ({sql}) to '{out_file.as_posix()}' (format parquet, compression zstd)"
            con.execute(copy_sql)
            described = con.execute(f"describe select * from '{out_file.as_posix()}'")
            columns = [(c, t) for c, t, *_ in described.fetchall()]
            n = con.execute(f"select count(*) from '{out_file.as_posix()}'").fetchone()[0]
            rows[name] = (n, columns)
            echo(f"  reference/{name}.parquet: {n:,} rows")

    (tmp / "README.md").write_text(_readme_reference(rows), encoding="utf-8")
    shutil.rmtree(ref_dir, ignore_errors=True)
    tmp.rename(ref_dir)
    return {name: n for name, (n, _) in rows.items()}
